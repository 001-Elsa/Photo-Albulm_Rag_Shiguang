CITY_NAMES = [c[0] for c in CITIES]

_EARTH_R = 6371.0


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = math.radians(lat2 - lat1), math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * _EARTH_R * math.asin(math.sqrt(a))


def nearest_city(lat: float | None, lon: float | None, max_km: float = 80.0) -> str | None:
    """最近城市名;坐标缺失或离所有已知城市都超过 max_km 时返回 None。"""
    if lat is None or lon is None:
        return None
    best_name, best_d = None, max_km
    for name, clat, clon in CITIES:
        # 粗筛:纬度差 1 度约 111km,先排除明显远的,避免全量三角函数
        if abs(clat - lat) * 111 > best_d:
            continue
        d = haversine_km(lat, lon, clat, clon)
        if d < best_d:
            best_name, best_d = name, d
    return best_name


def find_city_in_text(text: str) -> str | None:
    """查询文本里是否提到已知城市(最长匹配优先,避免"上海"匹配进"海口"这类问题)。"""
    hits = [c for c in CITY_NAMES if c in text]
    return max(hits, key=len) if hits else None
